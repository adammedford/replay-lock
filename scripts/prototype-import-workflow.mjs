import { mkdtemp, mkdir, readFile, writeFile, readdir, realpath, symlink, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createServer as createHttpServer } from 'node:http';
import { createServer } from 'vite';
import { replaylock } from '../dist/vite-plugin.js';
import { placementDependencies, qualifyPlacementSources } from './prototype-import-placement.mjs';
import { fixtureGenerationGate } from './prototype-import-generation.mjs';
import { attachLiveFixtureControls } from './prototype-import-live-attachment.mjs';

const library = fileURLToPath(new URL('../', import.meta.url));
const source = 'import { scalar } from "./helper.mjs"; export function result() { return scalar + 4; }';
const refused = () => new Error('GRAPH_REFUSED');

// The only caller supplies fixed trusted fixture configuration. No arbitrary
// config/plugin support, source-transform proof, attach or HMR is claimed.
export function fixtureImportGate() {
  let root;
  async function readGraph() {
    const sources = new Map();
    const active = new Set();
    async function visit(url) {
      if (active.has(url)) throw refused();
      if (sources.has(url)) return;
      if (sources.size >= 32) throw refused();
      active.add(url);
      const filename = path.join(root, url.slice(1));
      if (await realpath(filename) !== filename) throw refused();
      const text = await readFile(filename, 'utf8');
      if (Buffer.byteLength(text) > 65536) throw refused();
      sources.set(url, text);
      for (const dependency of placementDependencies(text, url)) await visit(dependency);
      active.delete(url);
    }
    await visit('/entry.mjs');
    qualifyPlacementSources(sources);
    return sources;
  }
  return {
    name: 'replaylock:prototype-fixture-import-gate', enforce: 'pre',
    async configResolved(configuration) { root = await realpath(configuration.root); },
    async load(id) {
      const relative = path.relative(root, id);
      if (relative.startsWith('..') || path.isAbsolute(relative) || relative.includes(path.sep) || !relative.endsWith('.mjs')) return;
      // This exact trusted infrastructure file is generated by the harness,
      // not an exception authorizing any application or dependency module.
      if (relative === 'vite.config.mjs') return;
      const sources = await readGraph();
      const text = sources.get('/' + relative);
      if (text === undefined) throw refused();
      // Return the checked bytes; do not leave a second filesystem read to Vite.
      return text;
    },
  };
}

export async function startImportWorkflow({ ownedTurns = false, evaluatorAttachment = false, liveAttachment, sealedAnalysis = false, preparedAnalysis, nativeRecipeIdentity = false, finalNode } = {}) {
  if ((evaluatorAttachment || liveAttachment !== undefined || sealedAnalysis) && !ownedTurns) throw new Error('ATTACHMENT_CONTEXT_REFUSED');
  if (preparedAnalysis !== undefined && (!sealedAnalysis || !['release', 'mutate', 'unguarded-mutate'].includes(preparedAnalysis))) throw new Error('ATTACHMENT_CONTEXT_REFUSED');
  if (typeof nativeRecipeIdentity !== 'boolean' || (nativeRecipeIdentity && (!ownedTurns || liveAttachment === undefined))) throw new Error('ATTACHMENT_CONTEXT_REFUSED');
  if (finalNode !== undefined && (!['release', 'mutate', 'unguarded-mutate', 'withheld-mutate'].includes(finalNode)
    || !nativeRecipeIdentity || preparedAnalysis !== 'release' || !sealedAnalysis
    || liveAttachment !== (['mutate', 'unguarded-mutate'].includes(finalNode) ? 'mutate' : 'release'))) throw new Error('ATTACHMENT_CONTEXT_REFUSED');
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'replaylock-import-workflow-')));
  let vite, host, manifest, analysisOwner, finalGuard;
  let preparedReady = false;
  let stopped = false;
  async function control(operation) {
    const response = await fetch(`${manifest.url}__replaylock/${operation}`, { method: 'POST',
      headers: { 'Content-Type': 'application/json', 'X-ReplayLock-Token': manifest.token }, body: '{}' });
    const result = await response.json();
    if (!response.ok) throw new Error(result.code);
    return result;
  }
  const stop = async () => { if (!stopped) { await control('stop'); stopped = true; } };
  const waitForObservation = async () => {
    const deadline = Date.now() + 10000;
    while (Date.now() < deadline) {
      if ((await control('status')).stored >= 1) return;
      await new Promise(resolve => setTimeout(resolve, 20));
    }
    throw new Error('OBSERVATION_TIMEOUT');
  };
  let shutdownPromise;
  const shutdown = () => shutdownPromise ??= (async () => {
    try { await vite?.close(); } finally {
      if (host?.listening) await new Promise((resolve, reject) => host.close(error => error ? reject(error) : resolve()));
    }
  })();
  const close = async () => {
    try { await shutdown(); } finally { analysisOwner?.release(); await rm(root, { recursive: true, force: true }); }
  };
  try {
    await mkdir(path.join(root, 'node_modules'));
    await symlink(library, path.join(root, 'node_modules/replaylock'), process.platform === 'win32' ? 'junction' : 'dir');
    await writeFile(path.join(root, 'package.json'), '{"name":"synthetic-import-workflow","private":true,"type":"module"}');
    await writeFile(path.join(root, 'package-lock.json'), '{"lockfileVersion":3}');
    await writeFile(path.join(root, 'entry.mjs'), source);
    await writeFile(path.join(root, 'helper.mjs'), 'export const scalar = 3;');
    // Fixed trusted UI infrastructure, outside the application entry closure.
    const begin = ownedTurns ? `const admission = await fetch('/__fixture_generation/begin', {method:'POST'});
          const body = await admission.json();
          if (!admission.ok) throw new Error(body.code);
          turn = body.token;` : '';
    const finish = ownedTurns ? `if (turn) {
            const response = await fetch('/__fixture_generation/finish', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({token:turn})});
            if (!response.ok) { output.textContent='HOST_FAILURE'; output.dataset.refused='true'; }
          }` : '';
    await writeFile(path.join(root, 'index.html'), `<!doctype html><button>Run synthetic graph</button><output></output>
      <script type="module">
        document.querySelector('button').onclick = async () => {
          ${ownedTurns ? `
          const output = document.querySelector('output');
          delete output.dataset.settled; delete output.dataset.refused; output.textContent='';
          let turn;
          try {
            ${begin}
            const application = await import('/entry.mjs');
            output.textContent = String(application.result());
          } catch (error) { output.textContent = error.message; output.dataset.refused='true'; }
          finally {
            try { ${finish} }
            catch { output.textContent='HOST_FAILURE'; output.dataset.refused='true'; }
            finally { output.dataset.settled='true'; }
          }
          ` : `
          const application = await import('/entry.mjs');
          const output = document.querySelector('output');
          output.textContent = String(application.result()); output.dataset.settled='true';
          `}
        };
      </script>`);
    const gateModule = ownedTurns ? new URL('./prototype-import-generation.mjs', import.meta.url).href : pathToFileURL(fileURLToPath(import.meta.url)).href;
    const factory = ownedTurns ? 'fixtureGenerationGate' : 'fixtureImportGate';
    const attachmentModule = new URL('./prototype-import-evaluator-attachment.mjs', import.meta.url).href;
    const configuration = `import { ${factory} } from ${JSON.stringify(gateModule)};
      ${evaluatorAttachment ? `import { fixtureReplayDeliveryAttachment } from ${JSON.stringify(attachmentModule)};` : ''}
      export default {plugins:[${factory}()${evaluatorAttachment ? ',fixtureReplayDeliveryAttachment()' : ''}]};`;
    await writeFile(path.join(root, 'vite.config.mjs'), configuration);
    if (sealedAnalysis) {
      const { sealFixtureAnalysis } = await import('./prototype-import-analysis-bootstrap.mjs');
      analysisOwner = sealFixtureAnalysis(root);
    }
    const gate = ownedTurns ? fixtureGenerationGate({ analysisCurrent: analysisOwner?.current }) : fixtureImportGate();
    host = createHttpServer((request, response) => { void (async () => {
      // This slice owns only the Node /invoke route. Do not expose an unchecked
      // client application route while claiming its Node closure was withheld.
      if (finalNode !== undefined && request.url !== '/invoke'
        && !/^\/__replaylock\/(?:start|stop|status)$/.test(request.url)) {
        response.statusCode = 409; response.end('{"code":"GRAPH_REFUSED"}'); return;
      }
      if (preparedAnalysis !== undefined && !preparedReady
        && (request.url === '/invoke' || /^\/[a-z][a-z-]*\.mjs(?:\?|$)/.test(request.url))) {
        response.statusCode = 409; response.end('{"code":"GRAPH_REFUSED"}'); return;
      }
      if (ownedTurns && request.url.startsWith('/__fixture_generation/')) {
        try {
          if (request.method !== 'POST') throw new Error('TURN_INVALID');
          let body;
          if (request.url === '/__fixture_generation/begin') body = {token:await gate.beginTurn()};
          else if (request.url === '/__fixture_generation/finish') {
            let input = '';
            for await (const chunk of request) { input += chunk; if (Buffer.byteLength(input) > 256) throw new Error('TURN_INVALID'); }
            await gate.finishTurn(JSON.parse(input).token); body = {finished:true};
          } else throw new Error('TURN_INVALID');
          response.setHeader('Content-Type', 'application/json'); response.end(JSON.stringify(body));
        } catch (error) {
          response.statusCode = 409;
          response.end(JSON.stringify({code:['GENERATION_CLOSED','TURN_BUSY','TURN_INVALID'].includes(error.code) ? error.code : 'GRAPH_REFUSED'}));
        }
        return;
      }
      if (ownedTurns && /^\/[a-z][a-z-]*\.mjs(?:\?|$)/.test(request.url)) {
        try { gate.assertDelivery(); if (request.url.includes('?')) throw new Error('GRAPH_REFUSED'); }
        catch { response.statusCode = 409; response.end('{"code":"GRAPH_REFUSED"}'); return; }
        if (liveAttachment === 'refuse' && request.url === '/entry.mjs') {
          // Exercise the actual client hook, then own its refusal response before
          // middleware-mode Vite can consume the error into a generic error page.
          try { await vite.environments.client.transformRequest(request.url); }
          catch (error) {
            response.statusCode = 409;
            response.setHeader('Content-Type', 'application/json');
            response.end(JSON.stringify({ code: error.code === 'EVALUATED_INPUT_REFUSED' ? error.code : 'GRAPH_REFUSED' }));
            return;
          }
        }
      }
      if (ownedTurns) {
        try {
          const pathname = decodeURIComponent(new URL(request.url, 'http://fixture.invalid').pathname);
          if (pathname.endsWith('.html') && pathname !== '/index.html') throw refused();
        } catch { response.statusCode = 409; response.end('{"code":"GRAPH_REFUSED"}'); return; }
      }
      if (request.url !== '/invoke') { vite.middlewares(request, response, () => { response.statusCode = 404; response.end(); }); return; }
      try {
        const invoke = async () => {
          await finalGuard?.prepare(); // Entire actual application closure first.
          const application = await vite.ssrLoadModule('/entry.mjs');
          return application.result();
        };
        const value = ownedTurns ? await gate.dispatch(invoke) : await invoke();
        response.setHeader('Content-Type', 'application/json');
        response.end(JSON.stringify({ value }));
      } catch (error) {
        response.statusCode = 409;
        response.end(JSON.stringify({ code: ownedTurns && ['GENERATION_CLOSED', 'EVALUATED_INPUT_REFUSED'].includes(error.code) ? error.code : 'GRAPH_REFUSED' }));
      }
    })(); });
    vite = await createServer({ root, configFile: false, envFile: false, logLevel: 'silent',
      plugins: [gate, replaylock({ dev: true })],
      optimizeDeps: { noDiscovery: true }, server: { middlewareMode: { server: host }, watch: null } });
    if (nativeRecipeIdentity) {
      const { acquireFixtureNativeIdentity } = await import('./prototype-import-native-identity.mjs');
      await acquireFixtureNativeIdentity(vite);
    }
    if (finalNode !== undefined) {
      const table = await analysisOwner.prepareNode(preparedAnalysis, true);
      const { createFinalNodeFixtureGuard } = await import('./prototype-import-final-node-guard.mjs');
      finalGuard = createFinalNodeFixtureGuard(vite, root, table, finalNode);
    }
    if (liveAttachment !== undefined) await attachLiveFixtureControls(vite, root, liveAttachment, finalGuard);
    if (preparedAnalysis !== undefined && finalNode === undefined) await analysisOwner.prepareNode(preparedAnalysis);
    await new Promise((resolve, reject) => { host.once('error', reject); host.listen(0, '127.0.0.1', resolve); });
    const deadline = Date.now() + 10000;
    while (!manifest && Date.now() < deadline) {
      try {
        const files = await readdir(path.join(root, '.replaylock/dev'));
        const name = files.find(file => file.endsWith('.json'));
        if (name) manifest = JSON.parse(await readFile(path.join(root, '.replaylock/dev', name), 'utf8'));
      } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (!manifest) await new Promise(resolve => setTimeout(resolve, 20));
    }
    if (!manifest) throw new Error('MANIFEST_TIMEOUT');
    await control('start');
    preparedReady = true;
    return { root, url: `http://127.0.0.1:${host.address().port}`, stop, close, shutdown, waitForObservation };
  } catch (error) { await close(); throw error; }
}
